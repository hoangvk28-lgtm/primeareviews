// Rebuilds data/guides-index.generated.ts from every data/guides/<slug>.json.
// Run after adding, removing, or editing guides: `npm run index`.
import fs from "node:fs";
import path from "node:path";

const dir = path.join(process.cwd(), "data", "guides");
const files = fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort();

const listings = [];
for (const f of files) {
  const g = JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"));
  if (`${g.slug}.json` !== f) throw new Error(`slug mismatch in ${f}`);
  listings.push({
    slug: g.slug,
    h1: g.h1,
    category: g.category,
    metaDescription: g.metaDescription,
    heroImage: g.heroImage,
    updatedAt: g.updatedAt,
    topScore: Math.max(...g.products.map((p) => p.score)),
  });
}

const out = `// AUTO-GENERATED by scripts/generate-index.mjs - do not hand-edit.
export interface GuideListing {
  slug: string;
  h1: string;
  category: string;
  metaDescription: string;
  heroImage: string;
  updatedAt: string;
  topScore: number;
}

export const guideRegistry: GuideListing[] = ${JSON.stringify(listings, null, 1)};

export const guideLoaders: Record<string, () => Promise<unknown>> = {
${listings.map((l) => `  ${JSON.stringify(l.slug)}: () => import("./guides/${l.slug}.json"),`).join("\n")}
};
`;
fs.writeFileSync(path.join(process.cwd(), "data", "guides-index.generated.ts"), out);
console.log(`Indexed ${listings.length} guides`);
